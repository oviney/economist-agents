#!/usr/bin/env python3
"""Skill eval harness (B-033) — make the guide layer measurable so it can shrink.

The audit found 8,031 lines of `SKILL.md` across 38 skills, plus a 210-line `CLAUDE.md`, a
2,601-line `.github/copilot-instructions.md`, a `GEMINI.md`, and a root
`copilot-instructions.md`. Nothing has ever measured whether any of it changes an outcome.
Product evals exist (`logs/article_evals.json`); harness evals did not.

Boeckeler on why that matters (SE Radio 730):

    "There are now some ways to do like skills evals — to have your skills and then write
    some scenarios and run them one time with the skill, one time without the skill and see
    if the skill actually makes the results better, or if the model would have been good at
    it by itself... many skills these days are actually generated by large language models.
    So people have large language models generate the skills and then I'm sometimes like,
    yeah, but then if the model already knows all of this."

Two deliberate design constraints:

* **Deterministic and keyless.** Scoring reuses the pipeline's own British-spelling and
  hedging dictionaries from `src/agent_sdk/_shared.py` — one source of truth, no LLM call,
  no auth to fail. A harness that costs money to run is a harness nobody runs, which is
  how the guide layer went unmeasured for this long.
* **Unmeasured is loud.** A skill with no `eval.yaml` reports ``UNMEASURED``. It must never
  read as validated, because the confident-looking silence is the actual problem.

This tool produces evidence. Deleting a skill remains the owner's call.

Usage::

    python -m scripts.skill_eval --list
    python -m scripts.skill_eval --skill economist-writing
    python -m scripts.skill_eval --list --strict     # non-zero if anything is unmeasured
"""

from __future__ import annotations

import argparse
import logging
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

logger = logging.getLogger(__name__)

REPO_ROOT = Path(__file__).resolve().parents[1]
SKILLS_DIR = REPO_ROOT / "skills"

#: Status for a skill that declares no scenarios. Deliberately not "PASS".
UNMEASURED = "UNMEASURED"

#: Status for a skill whose scenarios ran.
MEASURED = "MEASURED"


def _quality_dictionaries() -> tuple[dict[str, str], list[str]]:
    """Return the pipeline's British-spelling map and hedging phrases.

    Reused rather than duplicated so the eval scores against the same standard the Stage-4
    gates enforce. Falls back to a minimal set if the module moves, so `--list` never dies
    on an import.

    Returns:
        ``(american_to_british, hedging_phrases)``.

    """
    try:
        from src.agent_sdk._shared import _BRITISH_SPELLING, _HEDGING_PHRASES

        return dict(_BRITISH_SPELLING), list(_HEDGING_PHRASES)
    except Exception as exc:  # noqa: BLE001 — never let a scorer import break the CLI
        logger.warning("falling back to a minimal quality dictionary: %s", exc)
        return (
            {
                "organization": "organisation",
                "analyze": "analyse",
                "behavior": "behaviour",
            },
            ["one suspects", "it is worth noting"],
        )


@dataclass(frozen=True)
class SkillSummary:
    """Triage facts about one skill, cheap enough to compute for all of them."""

    name: str
    lines: int
    last_modified: str
    has_scenarios: bool

    @property
    def status(self) -> str:
        """Return ``MEASURED`` when scenarios exist, else ``UNMEASURED``."""
        return MEASURED if self.has_scenarios else UNMEASURED


@dataclass(frozen=True)
class Scenario:
    """One with/without pair declared in a skill's ``eval.yaml``."""

    name: str
    with_skill: str
    without_skill: str


@dataclass(frozen=True)
class EvalResult:
    """The outcome of evaluating one skill."""

    name: str
    status: str
    delta: float | None
    scenario_count: int


def _git_last_modified(path: Path) -> str:
    """Return the last commit date for ``path``, or 'unknown'.

    Git date beats filesystem mtime here: mtime is reset by every clone, so it cannot
    answer "has anyone touched this guide in six months?" — which is the triage question.

    Args:
        path: File to inspect.

    Returns:
        An ISO date string, or ``"unknown"``.

    """
    try:
        completed = subprocess.run(  # noqa: S603 — fixed argv, no shell
            ["git", "log", "-1", "--format=%cs", "--", str(path)],  # noqa: S607
            capture_output=True,
            text=True,
            cwd=REPO_ROOT,
            timeout=15,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return completed.stdout.strip() or "unknown"


def list_skills(skills_dir: Path | None = None) -> list[SkillSummary]:
    """Summarise every skill, largest first.

    Args:
        skills_dir: Directory of skill folders. Defaults to ``skills/``.

    Returns:
        Summaries sorted by line count descending — biggest context cost first, which is
        the order you want when deciding what to measure.

    """
    root = skills_dir or SKILLS_DIR
    if not root.is_dir():
        return []

    summaries: list[SkillSummary] = []
    for skill_md in sorted(root.glob("*/SKILL.md")):
        try:
            lines = len(skill_md.read_text(encoding="utf-8").splitlines())
        except OSError:
            continue
        summaries.append(
            SkillSummary(
                name=skill_md.parent.name,
                lines=lines,
                last_modified=_git_last_modified(skill_md),
                has_scenarios=bool(load_scenarios(skill_md.parent)),
            ),
        )
    return sorted(summaries, key=lambda s: s.lines, reverse=True)


def format_listing(summaries: list[SkillSummary]) -> str:
    """Render the triage table.

    Args:
        summaries: Output of :func:`list_skills`.

    Returns:
        A fixed-width table with a total, or a note when there is nothing to show.

    """
    if not summaries:
        return "No skills found."

    header = f"{'SKILL':<34}{'LINES':>7}  {'LAST COMMIT':<12}STATUS"
    rows = [
        f"{s.name:<34}{s.lines:>7}  {s.last_modified:<12}{s.status}" for s in summaries
    ]
    total = sum(s.lines for s in summaries)
    unmeasured = sum(1 for s in summaries if not s.has_scenarios)
    footer = (
        f"\n{len(summaries)} skills, {total} lines of guide. "
        f"{unmeasured} unmeasured — an unmeasured guide is a cost with an unknown benefit."
    )
    return "\n".join([header, "-" * len(header), *rows]) + footer


def load_scenarios(skill_dir: Path) -> list[Scenario]:
    """Read a skill's declared eval scenarios.

    Args:
        skill_dir: The skill's directory.

    Returns:
        Declared scenarios. Empty when ``eval.yaml`` is absent, unreadable, or malformed —
        all three mean "unmeasured", which is reported, not silently passed.

    """
    eval_path = skill_dir / "eval.yaml"
    try:
        raw = yaml.safe_load(eval_path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError):
        return []

    if not isinstance(raw, dict):
        return []

    scenarios: list[Scenario] = []
    for item in raw.get("scenarios") or []:
        if not isinstance(item, dict):
            continue
        scenarios.append(
            Scenario(
                name=str(item.get("name", "unnamed")),
                with_skill=str(item.get("with_skill", "")),
                without_skill=str(item.get("without_skill", "")),
            ),
        )
    return scenarios


def score_text(text: str) -> float:
    """Score prose against the pipeline's own deterministic quality rules.

    Not a general quality metric — a *comparator*. Its only job is to answer "is the
    with-skill output better than the without-skill output", so absolute values are
    meaningless and only the delta is reported.

    Args:
        text: Prose to score.

    Returns:
        0.0 for empty text; otherwise 100.0 minus penalties for American spellings and
        hedging phrases, floored at 0.

    """
    if not text.strip():
        return 0.0

    american_to_british, hedging = _quality_dictionaries()
    lowered = text.lower()

    americanisms = sum(1 for word in american_to_british if word in lowered)
    hedges = sum(1 for phrase in hedging if phrase.lower() in lowered)

    return max(0.0, 100.0 - (americanisms * 10.0) - (hedges * 15.0))


def evaluate_skill(skill_dir: Path) -> EvalResult:
    """Run one skill's scenarios and report the with/without delta.

    Args:
        skill_dir: The skill's directory.

    Returns:
        An :class:`EvalResult`. ``delta`` is None when the skill declares no scenarios;
        0.0 means the skill changed nothing measurable — the finding the audit expects for
        at least some of the 38.

    """
    scenarios = load_scenarios(skill_dir)
    if not scenarios:
        return EvalResult(
            name=skill_dir.name,
            status=UNMEASURED,
            delta=None,
            scenario_count=0,
        )

    deltas = [score_text(s.with_skill) - score_text(s.without_skill) for s in scenarios]
    return EvalResult(
        name=skill_dir.name,
        status=MEASURED,
        delta=sum(deltas) / len(deltas),
        scenario_count=len(scenarios),
    )


def main(argv: list[str] | None = None) -> int:
    """Run the harness from the command line.

    Returns:
        0 normally; 1 under ``--strict`` when any inspected skill is unmeasured, or when a
        named skill cannot be found.

    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--list", action="store_true", help="Triage table for all skills"
    )
    parser.add_argument("--skill", help="Evaluate one skill by directory name")
    parser.add_argument(
        "--skills-dir",
        type=Path,
        default=None,
        help="Override the skills directory (tests)",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Exit non-zero if any inspected skill is unmeasured",
    )
    args = parser.parse_args(argv)

    root = args.skills_dir or SKILLS_DIR

    if args.skill:
        result = evaluate_skill(root / args.skill)
        if not (root / args.skill).is_dir():
            sys.stderr.write(f"No such skill: {args.skill}\n")
            return 1
        if result.status == UNMEASURED:
            sys.stdout.write(
                f"{result.name}: {UNMEASURED} — no eval.yaml. Declare scenarios before "
                "treating this guide as load-bearing.\n",
            )
            return 1 if args.strict else 0
        sys.stdout.write(
            f"{result.name}: {MEASURED} over {result.scenario_count} scenario(s), "
            f"mean delta {result.delta:+.1f}\n",
        )
        return 0

    summaries = list_skills(root)
    sys.stdout.write(format_listing(summaries) + "\n")
    if args.strict and any(not s.has_scenarios for s in summaries):
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
